import type { Order } from '../types';

/** ISO date string N days before "now" — keeps the seed data evergreen across demo runs. */
function daysAgo(n: number): string {
  const d = new Date();
  d.setDate(d.getDate() - n);
  return d.toISOString().slice(0, 10);
}

function img(label: string, bg = 'F1EDE7', fg = '2B2320'): string {
  return `https://placehold.co/320x400/${bg}/${fg}?text=${encodeURIComponent(label)}`;
}

